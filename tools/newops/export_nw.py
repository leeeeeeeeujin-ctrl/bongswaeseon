# export one finished operator rig into the game: parts -> /home/claude/assets/nw_<id>_<part>.webp, rig -> nw_<id>_rig.json, clips appended into td/nwclips.js
import json, sys, os, re
from PIL import Image
ART = os.path.dirname(os.path.abspath(__file__)); A = "/home/claude/assets/"
def export(id, rigfile, clipsfile, glob, ver="", src=None):
    D = f"{ART}/{src or id}"
    r = json.load(open(f"{D}/{rigfile}")); names = set()
    def walk(o):
        if isinstance(o, dict):
            for k, v in list(o.items()):
                if k == "img" and isinstance(v, str): names.add(v); o[k] = f"nw_{id}{ver}_{v}"
                else: walk(v)
        elif isinstance(o, list):
            for v in o: walk(v)
    walk(r)
    for k, v in list(r.get("heads", {}).items()): names.add(v); r["heads"][k] = f"nw_{id}{ver}_{v}"
    for n in names:
        if os.path.exists(f"{D}/{n}.png"): Image.open(f"{D}/{n}.png").convert("RGBA").save(f"{A}nw_{id}{ver}_{n}.webp", quality=92, method=6)
    r.pop("meta", None)
    kfp = f"{D}/kf.json"
    if os.path.exists(kfp):   # finished keyframe drawings per clip
        kf = json.load(open(kfp))
        for c in kf.values():
            for f in c["frames"]:
                Image.open(f"{D}/{f['img']}.png").convert("RGBA").save(f"{A}nw_{id}{ver}_{f['img']}.webp", quality=90, method=6); f["img"] = f"nw_{id}{ver}_{f['img']}"
        r["kf"] = kf
    json.dump(r, open(f"{A}nw_{id}_rig.json", "w"), separators=(",", ":"))
    src = open(f"{D}/{clipsfile}").read()
    return f"// ---- {id} ----\n" + src.replace(f"root.{glob} = {{ CLIPS: C }};", f"(root.NWCLIPS = root.NWCLIPS || {{}}).{id} = {{ CLIPS: C }};")
if __name__ == "__main__":
    out = [open(f"{ART}/nwkf.js").read(), "// clips of the rigged trial operators (rig3.js runtime); generated by scratchpad newops/art/export_nw.py from each <id>/u_clips.js"]
    for spec in json.load(open(f"{ART}/export_list.json")): out.append(export(*spec))
    open("/home/claude/td/nwclips.js", "w").write("\n".join(out) + "\n")
